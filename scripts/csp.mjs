// Runs after `next build`. Writes out/_headers: the HTTP headers Cloudflare sends with every file.
//
// The important one is the Content-Security-Policy (CSP): a whitelist telling the browser where code may come from.
// Next.js puts small inline <script>s in every page. A static site can't use per-request nonces, so instead we hash
// each page's inline scripts (SHA-256) and allow exactly those hashes on exactly that page. Any script an attacker
// manages to inject has a different hash and is refused. No 'unsafe-inline' for scripts.
//
// usage: node scripts/csp.mjs   (reads SITE_INDEXABLE and NEXT_PUBLIC_CF_ANALYTICS_TOKEN like the build)

import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT = path.resolve(import.meta.dirname, "../out");

/** Executable inline scripts of a page (no src). JSON-LD and other data blocks are never executed, so they need no hash. */
export function inlineScripts(html) {
  const scripts = [];
  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const attrs = m[1];
    if (/\bsrc\s*=/i.test(attrs)) continue;
    const type = /\btype\s*=\s*["']?([^"'\s>]+)/i.exec(attrs)?.[1]?.toLowerCase();
    if (type && !["text/javascript", "module", "speculationrules"].includes(type)) continue;
    scripts.push(m[2]);
  }
  return scripts;
}

export const sha256 = (text) => `'sha256-${createHash("sha256").update(text, "utf8").digest("base64")}'`;

/** "ro.html" → "/ro", "ro/despre-noi.html" → "/ro/despre-noi", "404.html" → null (served for any unknown path). */
export function routeOf(relativeHtmlPath) {
  const p = relativeHtmlPath
    .split(path.sep)
    .join("/")
    .replace(/\.html$/, "");
  if (p === "404" || p === "_not-found") return null;
  return p === "index" ? "/" : `/${p.replace(/\/index$/, "")}`;
}

export function cspFor(hashes, { analytics }) {
  const script = ["'self'", ...new Set(hashes)];
  const connect = ["'self'"];
  if (analytics) {
    script.push("https://static.cloudflareinsights.com");
    connect.push("https://cloudflareinsights.com");
  }
  return [
    "default-src 'self'",
    `script-src ${script.join(" ")}`,
    // React puts style="" attributes on elements; inline styles can't run code, so this is the accepted trade-off.
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    `connect-src ${connect.join(" ")}`,
    "frame-src 'none'",
    "form-action 'self'",
    "base-uri 'self'",
    "object-src 'none'",
    "frame-ancestors 'none'",
    // No upgrade-insecure-requests: everything already loads from our own HTTPS origin (HSTS enforces it),
    // and on http://localhost it makes WebKit try HTTPS and fail the local tests.
  ].join("; ");
}

/** The whole _headers file. `pages` = [{ route, hashes }]. */
export function buildHeaders(pages, { indexable, analytics }) {
  const lines = [
    "# Generated by scripts/csp.mjs after every build — do not edit.",
    "/*",
    "  Strict-Transport-Security: max-age=31536000",
    "  X-Content-Type-Options: nosniff",
    "  Referrer-Policy: strict-origin-when-cross-origin",
    "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()",
    "  Cross-Origin-Opener-Policy: same-origin",
    "  X-Frame-Options: DENY",
  ];
  if (!indexable) lines.push("  X-Robots-Tag: noindex, nofollow");
  lines.push(
    "",
    "# Files whose names contain a content hash never change: cache them for a year.",
    "/_next/static/*",
    "  Cache-Control: public, max-age=31536000, immutable",
    "/_img/*",
    "  Cache-Control: public, max-age=31536000, immutable",
  );
  for (const { route, hashes } of pages) {
    lines.push("", route, `  Content-Security-Policy: ${cspFor(hashes, { analytics })}`);
  }
  return lines.join("\n") + "\n";
}

async function main() {
  const entries = await readdir(OUT, { recursive: true, withFileTypes: true });
  const pages = [];
  for (const e of entries) {
    if (!e.isFile() || !e.name.endsWith(".html")) continue;
    const rel = path.relative(OUT, path.join(e.parentPath, e.name));
    const route = routeOf(rel);
    if (!route) continue;
    const html = await readFile(path.join(OUT, rel), "utf8");
    pages.push({ route, hashes: inlineScripts(html).map(sha256) });
  }
  pages.sort((a, b) => a.route.localeCompare(b.route));
  if (pages.length > 90) throw new Error(`Cloudflare allows 100 _headers rules; we would write ${pages.length + 3}.`);
  const text = buildHeaders(pages, {
    indexable: process.env.SITE_INDEXABLE === "true",
    analytics: Boolean(process.env.NEXT_PUBLIC_CF_ANALYTICS_TOKEN),
  });
  await writeFile(path.join(OUT, "_headers"), text);
  console.log(`csp: out/_headers written for ${pages.length} page(s)`);
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
