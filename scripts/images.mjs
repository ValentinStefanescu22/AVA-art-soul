// Turns the source photos in assets/images/ into small, modern files the browser downloads:
// AVIF + WebP at several widths (public/_img/), plus a manifest (src/generated/images.ts) with each image's
// size and a tiny blurred preview shown while the real file loads. Static export disables next/image's optimiser,
// so this script does that job at build time. Re-runs are cheap: unchanged images are skipped.
//
// usage: node scripts/images.mjs

import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "assets/images");
const OUT = path.join(ROOT, "public/_img");
const MANIFEST = path.join(ROOT, "src/generated/images.ts");

export const WIDTHS = [480, 768, 1080, 1440, 1920, 2880];
const QUALITY = { avif: 55, webp: 74 };
// When the same image exists in several formats, the first one here is the master copy we encode from.
const SOURCE_PREFERENCE = [".png", ".jpg", ".jpeg", ".webp"];

/** "placeholder/grup.webp" → "placeholder-grup": the key used in code, e.g. <Picture image="placeholder-grup" />. */
export function keyOf(relativePath) {
  return relativePath
    .replace(/\.[^.]+$/, "")
    .split(path.sep)
    .join("-")
    .toLowerCase();
}

/** Widths to produce for a source image: never upscale, always include the original width as the largest. */
export function widthsFor(sourceWidth) {
  const ws = WIDTHS.filter((w) => w < sourceWidth);
  return [...ws, Math.min(sourceWidth, WIDTHS.at(-1))];
}

async function listSources(dir) {
  const entries = await readdir(dir, { withFileTypes: true, recursive: true });
  const files = entries
    .filter((e) => e.isFile() && SOURCE_PREFERENCE.includes(path.extname(e.name).toLowerCase()))
    .map((e) => path.relative(dir, path.join(e.parentPath, e.name)));
  // One master per key, chosen by SOURCE_PREFERENCE.
  const byKey = new Map();
  for (const rel of files.sort()) {
    const key = keyOf(rel);
    const rank = SOURCE_PREFERENCE.indexOf(path.extname(rel).toLowerCase());
    const prev = byKey.get(key);
    if (!prev || rank < prev.rank) byKey.set(key, { rel, rank });
  }
  return [...byKey.entries()].map(([key, { rel }]) => ({ key, rel }));
}

async function isFresh(outFile, sourceMtime) {
  try {
    return (await stat(outFile)).mtimeMs >= sourceMtime;
  } catch {
    return false;
  }
}

async function processImage({ key, rel }) {
  const file = path.join(SRC, rel);
  const input = await readFile(file);
  const { mtimeMs } = await stat(file);
  const meta = await sharp(input).metadata();
  const width = meta.autoOrient?.width ?? meta.width;
  const height = meta.autoOrient?.height ?? meta.height;
  // A short content hash in the file name lets the files be cached forever: a changed photo gets a new name.
  const hash = createHash("sha256").update(input).digest("hex").slice(0, 8);

  const variants = { avif: [], webp: [] };
  for (const w of widthsFor(width)) {
    for (const format of ["avif", "webp"]) {
      const name = `${key}-${w}-${hash}.${format}`;
      const out = path.join(OUT, name);
      if (!(await isFresh(out, mtimeMs))) {
        await sharp(input).autoOrient().resize({ width: w }).toFormat(format, { quality: QUALITY[format] }).toFile(out);
      }
      variants[format].push({ w, src: `/_img/${name}` });
    }
  }
  const tiny = await sharp(input).autoOrient().resize({ width: 16 }).blur(1).webp({ quality: 40 }).toBuffer();
  return { key, width, height, blur: `data:image/webp;base64,${tiny.toString("base64")}`, ...variants };
}

async function main() {
  await mkdir(OUT, { recursive: true });
  await mkdir(path.dirname(MANIFEST), { recursive: true });
  const sources = await listSources(SRC);
  const images = await Promise.all(sources.map(processImage));
  images.sort((a, b) => a.key.localeCompare(b.key));
  const body = Object.fromEntries(images.map(({ key, ...rest }) => [key, rest]));
  await writeFile(
    MANIFEST,
    `// Generated by scripts/images.mjs — do not edit. Re-run \`npm run images\` after changing assets/images/.\n` +
      `export const IMAGES = ${JSON.stringify(body, null, 2)} as const;\n` +
      `export type ImageKey = keyof typeof IMAGES;\n`,
  );
  console.log(`images: ${images.length} sources → public/_img/ (manifest: src/generated/images.ts)`);
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
